//! `tacho pr "<title>" -m "<description>"`: PR preflight verification, screenshot scope rules,
//! forbidden trailer/attribution/session-link checks, PR body formatting with proof commands
//! and outputs, and `--no-verify` (plus `--force-with-lease` when branch exists on remote) push.

use std::fs;
use std::io;
use std::path::Path;
use std::process::Command;

use tacho_core::decide::verify::{AreaRule, ProofSummary};

use super::prove::stray_screenshots_for_files;
use super::{
    emit_decision_event, find_worktree_root, is_internal_tacho_path, load_worktree_env,
    open_fleet_store, resolve_base_sha_for_worktree, tree_of_worktree,
};
use crate::cli::PrArgs;

/// Complete preflight input for `tacho pr`.
#[derive(Debug, Clone)]
pub struct PrPreflightInput {
    pub title: String,
    pub description: String,
    pub base_sha: String,
    pub head_sha: String,
    pub head_tree: String,
    pub dirty_files: Vec<String>,
    pub changed_files: Vec<String>,
    pub commits: Vec<(String, String)>,
    pub merge_commits: Vec<String>,
    pub proof: Option<ProofSummary>,
    pub stray_screenshots: Vec<String>,
    pub area_rules: Vec<AreaRule>,
    pub shots_anyway: bool,
}

fn has_co_authored_by_line(text: &str) -> bool {
    for line in text.lines() {
        let lower = line.trim_start().to_ascii_lowercase();
        if let Some(rest) = lower.strip_prefix("co-authored-by") {
            if rest.trim_start().starts_with(':') {
                return true;
            }
        }
    }
    false
}

fn has_generated_with_line(text: &str) -> bool {
    for line in text.lines() {
        let trimmed = line.trim().trim_start_matches('\u{1F916}').trim();
        let lower = trimmed.to_ascii_lowercase();
        for prefix in ["generated with ", "generated by "] {
            if let Some(idx) = lower.find(prefix) {
                let after = lower[idx + prefix.len()..].trim_start_matches(['[', '(', '"', '\'']);
                for marker in [
                    "claude", "codex", "gemini", "cursor", "copilot", "chatgpt", "ai", "agent",
                    "http://", "https://",
                ] {
                    if after.starts_with(marker) {
                        return true;
                    }
                }
            }
        }
    }
    false
}

fn has_session_link(text: &str) -> bool {
    let lower = text.to_ascii_lowercase();
    for tok in lower.split_whitespace() {
        let clean = tok.trim_matches(['(', ')', '[', ']', '<', '>', '"', '\'', ',', '.']);
        if (clean.starts_with("http://") || clean.starts_with("https://"))
            && (clean.contains("claude.ai/")
                || clean.contains("/session_")
                || clean.contains("/session-")
                || clean.contains("/session/"))
        {
            return true;
        }
        if let Some(id) = clean.strip_prefix("session_") {
            if id.len() >= 8
                && id
                    .bytes()
                    .all(|b| b.is_ascii_alphanumeric() || b == b'_' || b == b'-')
            {
                return true;
            }
        }
    }
    false
}

/// Inspect a text block (labeled `source`, e.g. `"commit a1b2c3d4"` or `"PR description"`)
/// for forbidden trailers, `"Generated with"` lines, session links, and robot emoji.
pub fn check_forbidden_attribution(source: &str, text: &str, errors: &mut Vec<String>) {
    if has_co_authored_by_line(text) {
        errors.push(format!(
            "{source} contains a forbidden 'Co-Authored-By:' trailer; amend to plain author commit"
        ));
    }
    if has_generated_with_line(text) {
        errors.push(format!(
            "{source} contains a forbidden 'Generated with' attribution line"
        ));
    }
    if has_session_link(text) {
        errors.push(format!("{source} contains a forbidden agent session link"));
    }
    if text.contains('\u{1F916}') {
        errors.push(format!(
            "{source} contains a forbidden robot attribution marker (\u{1F916})"
        ));
    }
}

/// Validate all PR preflight invariants and return every refusal reason at once.
pub fn validate_pr_preflight(input: &PrPreflightInput) -> Vec<String> {
    let mut errors = Vec::new();

    if input.title.trim().is_empty() {
        errors.push("PR title cannot be empty".to_string());
    }
    if input.description.trim().is_empty() {
        errors.push("PR description (-m) cannot be empty".to_string());
    }

    if input.commits.is_empty() || input.changed_files.is_empty() {
        let base_short = &input.base_sha[..input.base_sha.len().min(8)];
        errors.push(format!(
            "diff against base {base_short} is empty (no commits or changed files to open a PR)"
        ));
    }

    if !input.dirty_files.is_empty() {
        errors.push(format!(
            "working tree has uncommitted changes ({:?}); commit or revert them and re-run 'tacho prove'",
            input.dirty_files
        ));
    }

    if !input.merge_commits.is_empty() {
        let short_merges: Vec<&str> = input
            .merge_commits
            .iter()
            .map(|s| &s[..s.len().min(8)])
            .collect();
        errors.push(format!(
            "merge commits are not allowed in PR branch ({short_merges:?}); recreate as plain linear commits on base"
        ));
    }

    match &input.proof {
        None => {
            errors.push(
                "no proof found (.tachoproof/summary.json missing); run 'tacho prove' first"
                    .to_string(),
            );
        }
        Some(p) => {
            let failed: Vec<&str> = p
                .checks
                .iter()
                .filter(|c| !c.ok)
                .map(|c| c.name.as_str())
                .collect();
            if !p.ok || !failed.is_empty() || p.checks.is_empty() {
                errors.push(format!(
                    "proof did not pass (failed checks: {failed:?}); fix failures and re-run 'tacho prove'"
                ));
            }
            if p.tree != input.head_tree {
                errors.push(format!(
                    "proof is stale: proof tree {} does not match current worktree tree {}; run 'tacho prove' again",
                    &p.tree[..p.tree.len().min(12)],
                    &input.head_tree[..input.head_tree.len().min(12)]
                ));
            }
            for chk in &p.checks {
                check_forbidden_attribution(
                    &format!("proof check '{}'", chk.name),
                    &chk.output_tail,
                    &mut errors,
                );
            }
        }
    }

    for (sha, msg) in &input.commits {
        let short_sha = &sha[..sha.len().min(8)];
        check_forbidden_attribution(&format!("commit {short_sha}"), msg, &mut errors);
    }
    check_forbidden_attribution("PR title", &input.title, &mut errors);
    check_forbidden_attribution("PR description", &input.description, &mut errors);

    if !input.shots_anyway {
        if !input.stray_screenshots.is_empty() {
            errors.push(format!(
                "stray PNG screenshots outside touched screens: {:?} (revert with `git checkout -- <path>` or pass `--shots-anyway` / `TACHO_SHOTS_ANYWAY=1`)",
                input.stray_screenshots
            ));
        }

        let has_png = input.changed_files.iter().any(|f| f.ends_with(".png"));
        if !has_png && !input.area_rules.is_empty() {
            let touched_areas = tacho_core::decide::verify::areas_for_files(
                &input.changed_files,
                &input.area_rules,
            );
            for area in touched_areas {
                if let Some(rule) = input.area_rules.iter().find(|r| r.area == area) {
                    if rule.needs_screenshot {
                        errors.push(format!(
                            "touched area '{area}' requires an updated screenshot (.png)"
                        ));
                    }
                }
            }
        }
    }

    errors
}

/// Format the PR body from the description, optional base PR stack note, the `## Proof` summary table,
/// and each proof check's command (`$ <cmd>`) and output.
pub fn format_pr_body_with_outputs(
    description: &str,
    proof: &ProofSummary,
    base_pr: Option<u64>,
) -> String {
    let mut body = String::new();
    body.push_str(description.trim());
    body.push_str("\n\n");
    if let Some(bpr) = base_pr {
        body.push_str(&format!("Stacks on #{bpr}.\n\n"));
    }
    let tree_short = &proof.tree[..proof.tree.len().min(12)];
    let head_short = &proof.head[..proof.head.len().min(12)];
    body.push_str(&format!(
        "## Proof (tree `{tree_short}`, head `{head_short}`)\n\n"
    ));
    body.push_str("| Area | Units | Check | Command | Status | Duration |\n");
    body.push_str("|---|---|---|---|---|---|\n");
    for chk in &proof.checks {
        let area = chk.area.as_deref().unwrap_or("-");
        let units = if chk.units.is_empty() {
            "-".to_string()
        } else {
            chk.units.join(", ")
        };
        let status = if chk.ok { "PASS" } else { "FAIL" };
        let secs = (chk.duration_ms as f64) / 1000.0;
        body.push_str(&format!(
            "| {} | `{}` | `{}` | `{}` | {} | {:.2}s |\n",
            area, units, chk.name, chk.cmd, status, secs
        ));
    }

    if !proof.checks.is_empty() {
        body.push_str("\n### Proof Output\n");
        for chk in &proof.checks {
            let status = if chk.ok { "PASS" } else { "FAIL" };
            let secs = (chk.duration_ms as f64) / 1000.0;
            body.push_str(&format!(
                "\n#### `{}` ({status}, {secs:.2}s)\n```text\n$ {}\n",
                chk.name, chk.cmd
            ));
            if !chk.output_tail.trim().is_empty() {
                body.push_str(chk.output_tail.trim());
                body.push('\n');
            }
            body.push_str("```\n");
        }
    }
    body
}

/// Build the `git push` argument list for `branch`:
/// always passes `--no-verify`, and includes `--force-with-lease` when `branch` already exists on `origin`.
pub fn push_args_for_branch(branch: &str, remote_branch_exists: bool) -> Vec<String> {
    let mut args = vec!["push".to_string(), "--no-verify".to_string()];
    if remote_branch_exists {
        args.push("--force-with-lease".to_string());
    }
    args.extend([
        "-u".to_string(),
        "origin".to_string(),
        format!("HEAD:refs/heads/{branch}"),
    ]);
    args
}

/// Check whether `refs/heads/<branch>` already exists on `origin`.
pub fn check_remote_branch_exists(root: &Path, branch: &str) -> bool {
    Command::new("git")
        .args([
            "ls-remote",
            "--exit-code",
            "--heads",
            "origin",
            &format!("refs/heads/{branch}"),
        ])
        .current_dir(root)
        .output()
        .map(|o| o.status.success())
        .unwrap_or(false)
}

/// Executes `tacho pr "<title>" -m "<description>" [--dry-run] [--shots-anyway]`.
pub fn execute_pr(args: PrArgs) -> io::Result<()> {
    let store = open_fleet_store()?;
    let state = store.load()?;
    let cwd = std::env::current_dir()?;
    let root = find_worktree_root(&cwd);
    let env_map = load_worktree_env(&root);

    let base_sha = resolve_base_sha_for_worktree(&root, None, &env_map, &state)?;
    let base_pr = env_map
        .get("TACHO_BASE_PR")
        .or_else(|| env_map.get("BASE_PR"))
        .and_then(|s| s.parse::<u64>().ok())
        .or_else(|| {
            root.file_name()
                .and_then(|s| s.to_str())
                .and_then(|slug| state.worktrees.get(slug))
                .and_then(|w| w.base_pr)
        });

    let head_sha = String::from_utf8_lossy(
        &Command::new("git")
            .args(["rev-parse", "HEAD"])
            .current_dir(&root)
            .output()?
            .stdout,
    )
    .trim()
    .to_string();
    let head_tree = tree_of_worktree(&root)?;

    let status_out = Command::new("git")
        .args(["status", "--porcelain"])
        .current_dir(&root)
        .output()?;
    let dirty_files: Vec<String> = String::from_utf8_lossy(&status_out.stdout)
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty())
        .filter(|l| {
            let path_part = l.get(3..).unwrap_or(l).trim();
            !is_internal_tacho_path(path_part)
        })
        .map(String::from)
        .collect();

    let diff_out = Command::new("git")
        .args(["diff", "--name-only", &format!("{base_sha}..HEAD")])
        .current_dir(&root)
        .output()?;
    let changed_files: Vec<String> = String::from_utf8_lossy(&diff_out.stdout)
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !is_internal_tacho_path(l))
        .map(String::from)
        .collect();

    let rev_list_out = Command::new("git")
        .args(["rev-list", &format!("{base_sha}..HEAD")])
        .current_dir(&root)
        .output()?;
    let commit_shas: Vec<String> = String::from_utf8_lossy(&rev_list_out.stdout)
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty())
        .map(String::from)
        .collect();

    let mut commits = Vec::with_capacity(commit_shas.len());
    for sha in &commit_shas {
        let msg_out = Command::new("git")
            .args(["log", "-1", "--format=%B", sha])
            .current_dir(&root)
            .output()?;
        let msg = String::from_utf8_lossy(&msg_out.stdout).to_string();
        commits.push((sha.clone(), msg));
    }

    let merges_out = Command::new("git")
        .args(["rev-list", "--merges", &format!("{base_sha}..HEAD")])
        .current_dir(&root)
        .output()?;
    let merge_commits: Vec<String> = String::from_utf8_lossy(&merges_out.stdout)
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty())
        .map(String::from)
        .collect();

    let proof_path = root.join(".tachoproof/summary.json");
    let proof: Option<ProofSummary> = fs::read_to_string(&proof_path)
        .ok()
        .and_then(|s| serde_json::from_str(&s).ok());

    let stray_screenshots = stray_screenshots_for_files(&root, &changed_files);
    let shots_anyway = args.shots_anyway
        || std::env::var("TACHO_SHOTS_ANYWAY")
            .ok()
            .is_some_and(|v| v == "1" || v.eq_ignore_ascii_case("true"));

    let body_desc = args.message;
    let preflight_input = PrPreflightInput {
        title: args.title.clone(),
        description: body_desc.clone(),
        base_sha,
        head_sha: head_sha.clone(),
        head_tree,
        dirty_files,
        changed_files,
        commits,
        merge_commits,
        proof: proof.clone(),
        stray_screenshots,
        area_rules: state.area_rules.clone(),
        shots_anyway,
    };

    let errors = validate_pr_preflight(&preflight_input);
    if !errors.is_empty() {
        let joined = errors.join("\n  - ");
        let because = format!("pr preflight refused: {}", errors.join("; "));
        let _ = store.record_decision("verify", "pr_refused", &head_sha, &because);
        emit_decision_event("system", "verify:pr_refused", &because);
        return Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            format!("PR preflight refused:\n  - {joined}"),
        ));
    }

    let proof_summary = proof.expect("validated by validate_pr_preflight");
    let full_body = format_pr_body_with_outputs(&body_desc, &proof_summary, base_pr);

    if args.dry_run {
        println!("{full_body}");
        return Ok(());
    }

    let branch = String::from_utf8_lossy(
        &Command::new("git")
            .args(["rev-parse", "--abbrev-ref", "HEAD"])
            .current_dir(&root)
            .output()?
            .stdout,
    )
    .trim()
    .to_string();

    let remote_exists = check_remote_branch_exists(&root, &branch);
    let push_args = push_args_for_branch(&branch, remote_exists);
    let push_out = Command::new("git")
        .args(&push_args)
        .current_dir(&root)
        .output()?;
    if !push_out.status.success() {
        return Err(io::Error::other(format!(
            "git push failed: {}",
            String::from_utf8_lossy(&push_out.stderr).trim()
        )));
    }

    let gh_out = Command::new("gh")
        .args(["pr", "create", "--title", &args.title, "--body", &full_body])
        .current_dir(&root)
        .output();

    match gh_out {
        Ok(o) if o.status.success() => {
            let url = String::from_utf8_lossy(&o.stdout).trim().to_string();
            let because = format!("opened PR {url} for branch {branch}");
            let _ = store.record_decision("verify", "pr_opened", &branch, &because);
            emit_decision_event(&format!("agent:{branch}"), "verify:pr_opened", &because);
            println!("{url}");
            Ok(())
        }
        Ok(o) => Err(io::Error::other(format!(
            "gh pr create failed: {}",
            String::from_utf8_lossy(&o.stderr).trim()
        ))),
        Err(e) => Err(io::Error::other(format!(
            "failed to invoke `gh pr create`: {e}"
        ))),
    }
}
